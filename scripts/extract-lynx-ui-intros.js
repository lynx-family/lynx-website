const fs = require('fs');
const path = require('path');

const LYNX_UI_PACKAGE_NAME = '@lynx-js/lynx-ui';
const DEFAULT_PACKAGES_DIR = path.resolve(
  __dirname,
  '../.lynx-ui-source/packages',
);
const DEFAULT_OUTPUT_PATH = path.resolve(
  __dirname,
  '../sharedDocs/lynx-ui-intros.ts',
);
const EN_README_NAMES = ['README.md'];
const ZH_README_NAMES = ['README_zh.md', 'README.zh.md'];

// The first prose paragraph after the package H1 is the website summary.
// Stop at section boundaries instead of borrowing setup or API content.
const extractFirstParagraph = (content) => {
  const lines = content.split('\n');
  let foundHeader = false;
  const paragraph = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (!foundHeader) {
      if (trimmed.startsWith('# ')) {
        foundHeader = true;
      }
      continue;
    }

    if (trimmed.length === 0) {
      if (paragraph.length > 0) {
        break;
      }
      continue;
    }

    if (/^#{1,6}(?:\s|$)/.test(trimmed)) {
      break;
    }

    const isNonParagraphContent =
      trimmed.startsWith('import ') ||
      trimmed.startsWith('export ') ||
      trimmed.startsWith('<') ||
      trimmed.startsWith('{') ||
      trimmed.startsWith(':::');
    if (isNonParagraphContent) {
      if (paragraph.length > 0) {
        break;
      }
      continue;
    }

    paragraph.push(trimmed);
  }

  return paragraph.join(' ');
};

const extractIntroFromFile = (filePath) => {
  if (!fs.existsSync(filePath)) {
    return '';
  }

  return extractFirstParagraph(fs.readFileSync(filePath, 'utf8'));
};

// Package-level READMEs are authoritative; docs pages consume this output and
// must not become circular fallback sources.
const extractIntroFromReadmes = (packageDir, readmeNames) => {
  for (const readmeName of readmeNames) {
    const intro = extractIntroFromFile(path.join(packageDir, readmeName));
    if (intro) {
      return intro;
    }
  }

  return '';
};

const isLynxUiPackage = (packageName) =>
  packageName === LYNX_UI_PACKAGE_NAME ||
  packageName?.startsWith(`${LYNX_UI_PACKAGE_NAME}-`);

const missingIntroMessage = (packageName, pkg, language, readmeNames) =>
  `${packageName} (${pkg}): missing ${language} introduction; add a ` +
  `non-empty first paragraph after the H1 in ${readmeNames.join(' or ')}`;

// Validate the full source set so one run reports every upstream violation.
const collectIntros = (packagesDir) => {
  /** @type {Record<string, string>} */
  const enIntros = {};
  /** @type {Record<string, string>} */
  const zhIntros = {};
  const errors = [];

  for (const pkg of fs.readdirSync(packagesDir).sort()) {
    const packageDir = path.join(packagesDir, pkg);
    const packageJsonPath = path.join(packageDir, 'package.json');
    if (!fs.existsSync(packageJsonPath)) {
      continue;
    }

    const packageName = JSON.parse(
      fs.readFileSync(packageJsonPath, 'utf8'),
    ).name;
    if (!isLynxUiPackage(packageName)) {
      continue;
    }

    const enIntro = extractIntroFromReadmes(packageDir, EN_README_NAMES);
    if (enIntro) {
      enIntros[pkg] = enIntro;
    } else {
      errors.push(
        missingIntroMessage(packageName, pkg, 'English', EN_README_NAMES),
      );
    }

    const zhIntro = extractIntroFromReadmes(packageDir, ZH_README_NAMES);
    if (zhIntro) {
      zhIntros[pkg] = zhIntro;
    } else {
      errors.push(
        missingIntroMessage(packageName, pkg, 'Chinese', ZH_README_NAMES),
      );
    }
  }

  if (errors.length > 0) {
    throw new Error(
      `Cannot generate lynx-ui introductions:\n${errors
        .map((error) => `- ${error}`)
        .join('\n')}`,
    );
  }

  return { enIntros, zhIntros };
};

const sortRecord = (record) =>
  Object.fromEntries(
    Object.entries(record).sort(([a], [b]) => a.localeCompare(b)),
  );

const renderIntros = ({ enIntros, zhIntros }) =>
  `// This file is auto-generated by scripts/extract-lynx-ui-intros.js\n` +
  `// Do not edit manually.\n` +
  `\n` +
  `export const lynxUiIntros: Record<string, string> = ${JSON.stringify(
    sortRecord(enIntros),
    null,
    2,
  )};\n` +
  `\n` +
  `export const lynxUiIntrosZh: Record<string, string> = ${JSON.stringify(
    sortRecord(zhIntros),
    null,
    2,
  )};\n`;

// Collect before writing so validation failures preserve the last valid output.
const generateIntros = (packagesDir, outputPath) => {
  const intros = collectIntros(packagesDir);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, renderIntros(intros), 'utf8');
};

const main = () => {
  if (!fs.existsSync(DEFAULT_PACKAGES_DIR)) {
    console.warn(
      'lynx-ui source not found. Run pnpm prepare:fetch-lynx-ui first.',
    );
    return;
  }

  generateIntros(DEFAULT_PACKAGES_DIR, DEFAULT_OUTPUT_PATH);
  console.log(
    'Successfully extracted introductions to sharedDocs/lynx-ui-intros.ts!',
  );
};

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}

module.exports = {
  collectIntros,
  extractFirstParagraph,
  generateIntros,
  renderIntros,
};
